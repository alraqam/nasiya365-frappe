import frappe


def execute():
    """Пометить существующие договоры версией формулы 1.

    С 2026-09-01 срок рассрочки считается по календарю, а не как число платежей
    (решение владельца). Недельный график из 12 платежей длится 2,76 месяца, а
    процент брался за 12 — переплата в 4,35 раза.

    Уже подписанные договоры пересчитывать нельзя: у клиента на руках график с
    конкретными суммами. Версия 1 на документе означает «считать так, как
    посчитали при подписании», и при любом пересохранении договор сохранит свои
    цифры. Новые договоры получают версию 2 при создании.

    Патч НЕ меняет ни одной денежной суммы — только проставляет версию.
    Идемпотентен: договоры с уже заполненной версией не трогаются.
    Откат: обнулить formula_version, и договоры вернутся к поведению по умолчанию.
    """
    updated = frappe.db.sql(
        """UPDATE `tabInstallment Plan`
           SET formula_version = 1
           WHERE IFNULL(formula_version, 0) = 0"""
    )
    frappe.db.commit()
    frappe.logger().info(f"stamp_installment_formula_version: {updated}")
